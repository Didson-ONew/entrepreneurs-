#!/usr/bin/env node
/* ============================================================================
   The brief for Claude Design, written out of the engine.

   PROTOTYPE_COMPONENTS_PROMPT.md is what gets pasted into Claude Design to make the
   printed components. It used to be typed by hand and it went stale twice in a month:
   it carried the v19 cards and supplier web into a v23 table, and then v23's band
   multipliers into a table playing the trial rules. Every number in it now comes from
   EntrepreneursGame.jsx when this runs - the supplier web, the bills, the tiers, the
   sixty cards, the colours, the tiles - the same way check_rulebook.mjs reads the book.
   test_design_prompt.js fails when the committed file is not what this would write.

   Run: node make_design_prompt.mjs           (writes PROTOTYPE_COMPONENTS_PROMPT.md)
        node make_design_prompt.mjs --check   (exit 1 if the committed file is stale)
   ========================================================================== */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createContext, runInContext } from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EDITION } from "./rulebook.data.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "PROTOTYPE_COMPONENTS_PROMPT.md");

const src = readFileSync(path.join(here, "EntrepreneursGame.jsx"), "utf8");
const cut = src.indexOf("/* ============================== REACT UI ============================== */");
if (cut < 0) { console.error("engine shape changed - the REACT UI marker is gone"); process.exit(2); }
const box = {};
const sandbox = { box, console, Math, Set, Map, Object, Array, JSON, String, Number };
createContext(sandbox);
runInContext(src.slice(0, cut).replace(/^\s*(import|export)\s.*$/gm, "") + `
  box.E = { BP_DATA, INDUSTRIES, IND_NAME, IND_COLOR, BASE_PRICE, SCALING, PLAYER_COLORS, OPEX_TIER, OPEX_TIER_LABEL,
    ENTRY_GRADE, ENTRY_GRADE_LABEL, supplierBill, tierTable, cardFace, TILES, SUBURB_POOL, CENTER_POOL, DEMAND_ROWS,
    districtFamily, MEGACORP_TILES, MEGACORP_TIER, MEGACORP_TIER_MIN_PLAYERS, PERSONAS, STARTING, LOAN_REPAY_RATE,
    landAwardFor, LAND_AWARD_BASE, CASH_PER_EP, INDUSTRY_DEBUT_EP, DISCS_PER_PLAYER, COMPANY_SLOTS, PRICE_MIN, PRICE_MAX,
    MEGACORPS_TO_END, MEGACORP_TITHE_EP, STANDARD_QUARTERS, LONG_GAME_QUARTERS, workingTrackSlots, levelEP, buildBoard,
    mulberry32, TRIAL_RENT_STEP, PLOT_PER_STRUCTURE };`, sandbox);
const E = box.E;
const STATE = { variants: {} };            // the standard game: the trial rules
const LEVEL_EP = E.levelEP(STATE);
const I = E.INDUSTRIES;
const name = (i) => E.IND_NAME[i];
const $ = (n) => `$${n}`;
const suppliersOf = (ind) => I.filter((j) => j !== ind && E.BP_DATA.some((b) => b.ind === ind && b.deps.some((d) => d.ind === j)));
const buyersOf = (ind) => I.filter((j) => j !== ind && E.BP_DATA.some((b) => b.ind === j && b.deps.some((d) => d.ind === ind)));
const both = I.reduce((n, a) => n + suppliersOf(a).filter((b) => suppliersOf(b).includes(a)).length, 0);
const lattice = E.buildBoard(E.mulberry32(1)).priceLattice;
const latticeRows = [];
for (let r = 0; r <= 8; r++) {
  const row = [];
  for (let c = 0; c <= 8; c++) row.push(lattice[`${r},${c}`] === undefined ? "." : String(lattice[`${r},${c}`]));
  latticeRows.push(row.join(" "));
}
const combo = (c) => Object.entries(c).map(([l, n]) => `${n} × L${l}`).join(" + ");
const pays = (xs) => xs.map($).join(" + ");
const tierCell = (t, k) => (k === 0 ? $(t.pays[0]) : `${t.icons[k]}+ icons & ${$(t.price[k])}+ → ${$(t.pays[k])}`);

const md = [];
const P = (s = "") => md.push(s);

P(`# Prompt for Claude Design — physical prototype components`);
P();
P(`<!-- GENERATED by make_design_prompt.mjs from EntrepreneursGame.jsx. Do not edit by hand:`);
P(`     change the engine or the generator and run \`node make_design_prompt.mjs\`. -->`);
P();
P(`Copy everything below the line into Claude Design. Every number in it is read from`);
P(`the rules engine as the online game plays it: ${EDITION} with the trial rules of the`);
P(`playtest sheet of 23 November 2026 - round supplier bills, three earning tiers per card,`);
P(`and rent by plot value. The rulebook's Trial chapter describes the same rules.`);
P();
P(`---`);
P();
P(`I'm prototyping a medium-heavy economic euro board game called **Entrepreneurs** and I`);
P(`need a complete set of print-and-play components. I'll print them at home on A4 and US`);
P(`Letter, cut them by hand and play on a table - so design for *that*, not for a factory.`);
P();
P(`Build me a **design system first, then the components**, as separate artboards I can`);
P(`print one per sheet.`);
P();
P(`## What the game is`);
P();
P(`2–6 players build companies in a 4×4 city of districts. Every company pays a bill each`);
P(`quarter to companies in *other* industries - its suppliers - and those payments are the`);
P(`heart of the game. Building a company pushes its own industry's price down $1 and each of`);
P(`its suppliers' prices up $1, so the market is the sum of what the table has built.`);
P();
P(`The game is ${E.STANDARD_QUARTERS} quarters over 2 years (a three-year variant plays ${E.LONG_GAME_QUARTERS}). Each quarter has three`);
P(`phases: **Planning** (place workers), **Action** (tracks resolve, take actions) and`);
P(`**Closing** (bills and rent are paid, every company collects its tier, the industry pots`);
P(`are shared, a Logistic Hub opens; at Q4 and Q8 the land awards and the loan buy-back).`);
P(`A second Megacorp calls the following quarter as the last one.`);
P();
P(`**How a company earns.** It counts the demand icons of its industry it can reach and`);
P(`collects the best of three tiers printed on its card that it *fully* meets: enough icons`);
P(`AND a market price at or above the one printed. Otherwise it collects the Minimum. The`);
P(`amounts are printed in dollars - nothing is multiplied at the table.`);
P();
P(`The tone should be **corporate-modern, not sci-fi and not cute**: an annual report or an`);
P(`architect's site plan rather than a cartoon city. Clean, confident, information-dense but`);
P(`legible across a table at arm's length.`);
P();
P(`## Non-negotiable constants`);
P();
P(`These are the game's actual values. Do not invent, round, or "improve" them.`);
P();
P(`**Six industries.** The colours are checked in CIE Lab against the three colour-vision`);
P(`deficiencies (worst pair 27.3 apart); use them exactly.`);
P();
P(`| Code | Name | Colour | Base price | Grows | Running cost | Entry grade |`);
P(`|---|---|---|---|---|---|---|`);
for (const i of I) P(`| ${i} | ${name(i)} | \`${E.IND_COLOR[i]}\` | ${$(E.BASE_PRICE[i])} | ${E.SCALING[i] === "H" ? "Horizontal (spreads)" : "Vertical (stacks)"} | ${E.OPEX_TIER_LABEL[E.OPEX_TIER[i]]} | ${E.ENTRY_GRADE_LABEL[E.ENTRY_GRADE[i]]} |`);
P();
P(`**Accessibility is the most important constraint.** Give every industry a second,`);
P(`redundant channel - a distinct logo or glyph - and print its two-letter code beside it`);
P(`wherever the industry appears. A player must be able to play the whole game in greyscale.`);
P();
P(`**Player colours** (up to 6): ${E.PLAYER_COLORS.map((c) => `\`${c}\``).join(" ")}. A disc shows *who*, a block`);
P(`shows *what*, so a disc must never be read as an industry: pair the player colour with a`);
P(`shape or a ring, never colour alone.`);
P();
P(`**Price track:** ${$(E.PRICE_MIN)} to ${$(E.PRICE_MAX)}, one marker per industry, one cell per whole dollar. Mark each`);
P(`industry's base price.`);
P();
P(`**Other values:** ${E.DISCS_PER_PLAYER} discs per player · ${E.COMPANY_SLOTS} company bays (a sixth with the IPO tile) · ${E.INDUSTRY_DEBUT_EP} EP the first time`);
P(`a player builds in an industry · ${LEVEL_EP} EP a level when built and again when upgraded · cash scores 1 EP per`);
P(`full ${$(E.CASH_PER_EP)} · loans ${$(20)} for a disc, −5 EP each unpaid, bought back for ${$(E.LOAN_REPAY_RATE[4])} at the end of`);
P(`Year 1 and ${$(E.LOAN_REPAY_RATE[8])} at Year 2 (${$(E.LOAN_REPAY_RATE[12])} at Year 3 in the three-year game) · land awards at each year end`);
P(`to the outright leader in plots built on and in districts stood in: ${E.LAND_AWARD_BASE} EP + the player count`);
P(`(${E.landAwardFor(2).sole} at two seats, ${E.landAwardFor(6).sole} at six) · ${E.MEGACORPS_TO_END} Megacorps call the end · a Megacorp HQ banks its industry's`);
P(`price ÷ its tile's tier as EP every quarter and pays ${E.MEGACORP_TITHE_EP} EP a quarter to each rival company beside it.`);
P();
P(`## The supplier web`);
P();
P(`Every industry buys from exactly three others and sells to exactly three others; ${both}`);
P(`of the eighteen links run both ways. Draw it as a real graph, not a ring.`);
P();
P("```");
for (let k = 0; k < I.length; k += 2) P(`${I[k]} buys from  ${suppliersOf(I[k]).join(", ")}        ${I[k + 1]} buys from  ${suppliersOf(I[k + 1]).join(", ")}`);
P("```");
P();
P(`## Pay: the supplier bill`);
P();
P(`A company pays its suppliers one round total each quarter, set by its industry's running`);
P(`cost and its level; every level doubles it. One supplier takes all of it, two take half`);
P(`each, and a card that starts at Level 3 prints three suppliers: the first takes half and`);
P(`the other two a quarter each. Upgrading doubles what each supplier is paid.`);
P();
P(`| Running cost | Industries | Level 1 | Level 2 | Level 3 | Level 4 |`);
P(`|---|---|---|---|---|---|`);
for (const t of [1, 2, 3]) {
  const inds = I.filter((i) => E.OPEX_TIER[i] === t);
  P(`| ${E.OPEX_TIER_LABEL[t]} | ${inds.map(name).join(", ")} | ${[1, 2, 3, 4].map((l) => $(E.supplierBill(inds[0], l))).join(" | ")} |`);
}
P();
P(`## Earn: the three tiers`);
P();
P(`Minimum, middle and top. Each tier is a margin over the card's own bill, kinder the harder`);
P(`the industry is to enter. The icon counts are per company level; the price is the market`);
P(`price the industry's marker sits on.`);
P();
P(`| Industry | Level | Minimum pays | Middle tier | Top tier |`);
P(`|---|---|---|---|---|`);
for (const i of I) for (let l = 1; l <= 4; l++) {
  const t = E.tierTable(i, l);
  P(`| ${name(i)} | ${l} | ${$(t.pays[0])} | ${tierCell(t, 1)} | ${tierCell(t, 2)} |`);
}
P();
P(`## Rent`);
P();
P(`A company standing on another player's plot pays that owner, per floor, $1 for every full`);
P(`$${E.TRIAL_RENT_STEP} the plot is worth (never less than $1). A plot is worth its road price plus $${E.PLOT_PER_STRUCTURE} for each`);
P(`structure on it or orthogonally touching it. Nothing is owed on your own land.`);
P();
P(`## The components I need`);
P();
P(`### 1. The city board`);
P(`A 4×4 grid of **16 districts**. Each district is a 3×3 block in which **4 of the 8 compass`);
P(`positions hold a plot** and the centre never does - the centre carries the district's name`);
P(`and its demand grid. **64 plots** in all. Two plots are neighbours if they are orthogonally`);
P(`adjacent on the underlying 12×12 grid, across district borders too, so never draw districts`);
P(`as tidy 2×2 blocks. The four centre districts are always FC, IA, CC and LM, shuffled into the`);
P(`middle 2×2; twelve of the ${E.SUBURB_POOL.length} suburb tiles are drawn for the ring.`);
P();
P(`The **road prices** are fixed by position and can be printed on the board: the 9×9 lattice`);
P(`below sits over the district grid (even rows and columns are roads; "." is a district's`);
P(`middle). A corner plot reads its district's corner, an edge plot the middle of that edge.`);
P();
P("```");
for (const r of latticeRows) P(r);
P("```");
P();
P(`### 2. Twenty district tiles, demand grid included`);
P(`One per district. Each shows its four plots at their compass positions and, in the middle,`);
P(`a **4×4 grid of demand icons**: four rows, one industry each, and four columns numbered 1–4 -`);
P(`the company level that counts that column. **All four rows are open from the first`);
P(`quarter.** The first and last rows are always the same industry. Nothing is ever placed on`);
P(`an icon: players count them, so the grid only has to read clearly across the table.`);
P();
P(`| Tile | Plots | Row 1 | Row 2 | Row 3 | Row 4 |`);
P(`|---|---|---|---|---|---|`);
for (const t of [...E.CENTER_POOL, ...E.SUBURB_POOL]) P(`| ${t} | ${E.TILES[t].join(", ")} | ${E.DEMAND_ROWS[E.districtFamily(t)].join(" | ")} |`);
P();
P(`### 3. Sixty Blueprint cards`);
P(`Poker size (63×88 mm), nine to an A4 sheet with cut marks. Ten per industry: five that start`);
P(`at Level 1, three at Level 2, two at Level 3. Each card shows, in this order of importance:`);
P();
P(`- **Earn:** the three tiers - Minimum, then each tier's icons, price and amount.`);
P(`- **Pay:** each supplier (logo + code) and the amount it is paid.`);
P(`- Name, industry, **level**, and whether it spreads or stacks.`);
P(`- **Build:** the cost and how many owned plots it needs; the EP it scores when built.`);
P(`- **Upgrade:** the cost again plus one more owned plot (spreading) or floor (stacking), and`);
P(`  the EP it scores. Every number that changes on upgrade is printed after a slash, in grey:`);
P(`  the upgraded tiers, the upgraded bill.`);
P(`- **Sell / liquidate:** what the card fetches in hand, and what the company fetches built.`);
P();
P(`The full card list is the appendix at the end.`);
P();
P(`### 4. Sixteen Megacorp tiles`);
P(`Claimed by merging an exact combination of company levels. Each shows a name, the`);
P(`combination, a one-off EP award and a **tier from 1 to 4**. The tier is a *divisor*: the`);
P(`headquarters banks its industry's price ÷ tier as EP every quarter. **Tier 1 is the best.**`);
P(`Make the divisor as prominent as the EP.`);
P();
P(`| Name | Combination | EP | Tier | In play from |`);
P(`|---|---|---|---|---|`);
for (const [n, c, ep] of E.MEGACORP_TILES) { const tier = E.MEGACORP_TIER[n]; P(`| ${n} | ${combo(c)} | ${ep} | ${tier} | ${E.MEGACORP_TIER_MIN_PLAYERS[tier]} players |`); }
P();
P(`### 5. Six persona cards`);
P(`One dealt to each player; the rest sit out.`);
P();
for (const p of Object.values(E.PERSONAS)) P(`- **${p.name}** (${p.ind}) — ${p.blurb}`);
P();
P(`### 6. Money`);
P(`Printed notes, about 44 × 88 mm, 8 or 12 to an A4 sheet: **$1, $2, $5, $10, $20, $50**. Bills`);
P(`come in fives, so the $5 and $10 are the busiest notes; make all six easy to tell apart by`);
P(`colour, size and number position together.`);
P();
P(`### 7. Player pieces (printed fallbacks; I 3D-print the rest)`);
P(`- **${E.DISCS_PER_PLAYER} discs per player.** A disc under a building marks who owns the *land*; a disc on top`);
P(`  marks who owns the *business*.`);
P(`- **Company blocks, levels 1–4** - stack height reads as level.`);
P(`- **A Megacorp HQ marker**, a **Logistic Hub** token (one a quarter) and **Retail branch** tokens.`);
P(`- **2 workers per player** (3 at a two-player game).`);
P();
P(`### 8. Action tracks`);
P(`Workers are placed **left to right**; each track resolves **right to left**, and a worker takes`);
P(`one action plus one for every worker placed after it. Make both directions visible on the board.`);
P();
P(`- **Raise Capital** (LOAN, SELL), **M&A** (BUY, LAUNCH), **R&D** (RESEARCH, UPGRADE) - ${E.workingTrackSlots(4)} slots each at`);
P(`  2–4 players, ${E.workingTrackSlots(5)} at five, ${E.workingTrackSlots(6)} at six.`);
P(`- **Board Meeting** (GO PUBLIC, REPOSITION) - always 2 seats, the second opening with the IPO tile.`);
P();
P(`### 9. Player aid (double-sided, one per player)`);
P(`Front: the three phases, with Closing as a checklist - bills and rent, every company collects`);
P(`its tier, Megacorp dividends and tithe, the pots are shared, the hub, the year end. Back: the`);
P(`supplier web, the bill table, the rent rule and the scoring summary.`);
P();
P(`### 10. Small bits`);
P(`A **quarter track** of ${E.STANDARD_QUARTERS} (Q4 and Q8 marked as year ends with the land awards and the buy-back;`);
P(`Q9–Q${E.LONG_GAME_QUARTERS} dashed for the three-year variant), an **EP track**, **loan tokens**, a **first-player marker**, and`);
P(`the **IPO tile** (to the first player to form a Megacorp: a sixth company bay and Board`);
P(`Meeting's second seat, no EP).`);
P();
P(`## How I want it delivered`);
P();
P(`1. **A design system artboard first** - palette with the exact hexes above, the six industry`);
P(`   logos, type scale, and the rules for how a component is built.`);
P(`2. **One artboard per component type**, at real print size, laid out for A4 with US Letter`);
P(`   inside the safe area.`);
P(`3. **Greyscale-safe** - show one component in greyscale to prove the logos carry the information.`);
P(`4. **No bleed, visible cut lines**, generous inner margins.`);
P();
P(`## Starting capital and draft`);
P();
P(`Seats are drawn at random; later seats get less cash but more starting cards. The decks are`);
P(`shuffled whole and drafted in reverse seat order from the face-up top cards.`);
P();
P(`| Players | Seat 1 | Seat 2 | Seat 3 | Seat 4 | Seat 5 | Seat 6 |`);
P(`|---|---|---|---|---|---|---|`);
for (const n of Object.keys(E.STARTING).map(Number).sort((a, b) => a - b)) P(`| ${n} | ${Array.from({ length: 6 }, (_, k) => (E.STARTING[n][k] ? `${$(E.STARTING[n][k][0])} / ${E.STARTING[n][k][1]}` : "—")).join(" | ")} |`);
P();
P(`## Appendix — the 60 Blueprints`);
P();
P(`Each card: code, name and starting level; build cost and plots; **pay** - what each supplier is`);
P(`handed; **earn** - the Minimum, then the middle and top tiers as icons and price = amount; the`);
P(`same two lines once upgraded; and what the card sells for in hand and as a company.`);
for (const i of I) {
  P();
  P(`**${name(i)}** (${i}, base ${$(E.BASE_PRICE[i])}, ${E.SCALING[i] === "H" ? "spreads" : "stacks"}, ${E.OPEX_TIER_LABEL[E.OPEX_TIER[i]]} running cost, ${E.ENTRY_GRADE_LABEL[E.ENTRY_GRADE[i]]} to enter)`);
  for (const bp of E.BP_DATA.filter((b) => b.ind === i)) {
    const f = E.cardFace(STATE, bp);
    const pay = (xs) => f.suppliers.map((s, k) => `${s} ${$(xs[k])}`).join(" + ");
    const earn = (t) => `Minimum ${$(t.pays[0])} · middle ${t.icons[1]}+ icons & ${$(t.price[1])}+ = ${$(t.pays[1])} · top ${t.icons[2]}+ icons & ${$(t.price[2])}+ = ${$(t.pays[2])}`;
    P(`- **${f.code} ${f.name}** · L${f.level} · build ${$(f.build)} on ${f.plots} plot${f.plots > 1 ? "s" : ""} · sell ${$(f.sellCard)} in hand, ${$(f.sellCompany)} built`);
    P(`  - pay ${pay(f.pay)} · earn ${earn(f.earn)}`);
    if (f.payNext) P(`  - upgraded to L${f.level + 1}: pay ${pay(f.payNext)} · earn ${earn(f.earnNext)}`);
  }
}
const text = md.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== text) { console.error("PROTOTYPE_COMPONENTS_PROMPT.md is stale - run node make_design_prompt.mjs"); process.exit(1); }
  console.log("PROTOTYPE_COMPONENTS_PROMPT.md matches the engine");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.basename(OUT)} (${text.split("\n").length} lines)`);
}
