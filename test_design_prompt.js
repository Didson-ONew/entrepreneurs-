/* The Claude Design brief says what the engine says.

   PROTOTYPE_COMPONENTS_PROMPT.md is pasted into Claude Design to make the printed
   components, and it went stale twice when it was typed by hand. It is generated by
   make_design_prompt.mjs now; this fails when the committed file differs from what the
   engine would write, and spot-checks a few figures against the engine directly.

   Run: node test_design_prompt.js */
const { execFileSync } = require("child_process");
const fs = require("fs"), path = require("path"), vm = require("vm");
let fails = 0;
const check = (w, ok, note = "") => { if (!ok) fails++; console.log(`${ok ? "  ok  " : " FAIL "} ${w}${note ? `  [${note}]` : ""}`); };

let fresh = true, why = "";
try { execFileSync("node", [path.join(__dirname, "make_design_prompt.mjs"), "--check"], { encoding: "utf8", stdio: "pipe" }); }
catch (e) { fresh = false; why = String(e.stderr || e.message).trim(); }
check("the committed brief is what the engine generates", fresh, why);

const src = fs.readFileSync(path.join(__dirname, "EntrepreneursGame.jsx"), "utf8");
const box = {};
const sb = { console, Math, Set, Map, Object, Array, JSON, String, Number, box };
vm.createContext(sb);
vm.runInContext(src.slice(0, src.indexOf("/* ============================== REACT UI ============================== */")).replace(/^\s*(import|export)\s.*$/gm, "")
  + ";box.E = { BP_DATA, INDUSTRIES, IND_COLOR, PLAYER_COLORS, tierTable, supplierBill, LOAN_REPAY_RATE };", sb);
const E = box.E;
const md = fs.readFileSync(path.join(__dirname, "PROTOTYPE_COMPONENTS_PROMPT.md"), "utf8");
check("every one of the sixty cards is listed", E.BP_DATA.every((b) => md.includes(`**${b.code} ${b.name}**`)));
check("every industry colour and player colour is quoted",
  E.INDUSTRIES.every((i) => md.includes(E.IND_COLOR[i])) && E.PLAYER_COLORS.every((c) => md.includes(c)));
const sup = (i) => E.INDUSTRIES.filter((j) => j !== i && E.BP_DATA.some((b) => b.ind === i && b.deps.some((d) => d.ind === j)));
check("the supplier web is the cards' web", E.INDUSTRIES.every((i) => md.includes(`${i} buys from  ${sup(i).join(", ")}`)));
const t = E.tierTable("HC", 2);
check("a tier row matches the engine (Healthcare L2)",
  md.includes(`| Healthcare | 2 | $${t.pays[0]} | ${t.icons[1]}+ icons & $${t.price[1]}+ → $${t.pays[1]} | ${t.icons[2]}+ icons & $${t.price[2]}+ → $${t.pays[2]} |`));
check("the bill table matches the engine (High, Level 3)", md.includes(`$${E.supplierBill("HC", 3)}`));
check("the buy-back rates are quoted", [4, 8, 12].every((q) => md.includes(`$${E.LOAN_REPAY_RATE[q]}`)));
check("nothing of the band rule is left",
  !/multipl(y|ied|ier) the|band table|\$\$\$/i.test(md.replace(/nothing is multiplied at the table/i, "")));

console.log(fails ? `\n${fails} check(s) failed\n` : "\nall checks passed\n");
process.exit(fails ? 1 : 0);
